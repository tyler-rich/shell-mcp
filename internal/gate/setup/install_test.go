// host is the fake host with what the gate installer reads beyond setupx.
type host struct {
	*setuptest.Fake
	pol        *policy.Policy
	polErr     error
	sandboxErr error
	credErr    error
	mem        uint64
	scan       setup.ScanResult
	scanned    [][]uint32
	runAs      []*execx.Credential
	checkOut   setupx.Output
	// sshdOverride makes sshd -T -C for the account report these values.
	sshdOverride map[string]string
	sshService   bool
	sshSocket    bool
	strictModes  string
	// order records writes and runs, in order.
	order []string
}

func (h *host) LoadPolicy(_, _ string) (*policy.Policy, error) {
	if h.polErr != nil {
		return nil, h.polErr
	}
	return h.pol, nil
}

func (h *host) CheckSandbox(*policy.Policy) (int, error) { return 6, h.sandboxErr }

func (h *host) CredentialSupported() error { return h.credErr }

func (h *host) MemTotal() (uint64, error) { return h.mem, nil }

func (h *host) OwnerScan(uids, gids []uint32, _ []string) (setup.ScanResult, error) {
	h.order = append(h.order, "owner-scan")
	h.scanned = append(h.scanned, append(slices.Clone(uids), gids...))
	return h.scan, nil
}

func (h *host) RunAs(cred *execx.Credential, _ int, _ ...string) (setupx.Output, error) {
	h.order = append(h.order, "check-policy")
	h.runAs = append(h.runAs, cred)
	return h.checkOut, nil
}

func (h *host) WriteFile(p string, data []byte, mode os.FileMode, owner setupx.Owner) error {
	h.order = append(h.order, "write "+p)
	return h.Fake.WriteFile(p, data, mode, owner)
}

func (h *host) Mkdir(p string, mode os.FileMode, owner setupx.Owner) error {
	h.order = append(h.order, "mkdir "+p)
	return h.Fake.Mkdir(p, mode, owner)
}

// sshd answers sshd and systemctl as a real host would, from the fake's
// files: -T -C for the drop-in's account shows the block's values.
func (h *host) programs(f *setuptest.Fake, prog string, args []string) (setupx.Output, error) {
	h.order = append(h.order, strings.TrimPrefix(prog, "/usr/sbin/")+" "+strings.Join(args, " "))
	switch prog {
	case setupx.Sshd:
		if slices.Equal(args, []string{"-t"}) {
			return setupx.Output{}, nil
		}
		vals := map[string]string{}
		for k, v := range sshdDefaults {
			vals[k] = v
		}
		vals["strictmodes"] = h.strictModes
		if len(args) == 3 && args[1] == "-C" {
			user := strings.TrimPrefix(strings.Split(args[2], ",")[0], "user=")
			if d, ok := f.Get(dropPath); ok && strings.HasPrefix(d, "Match User "+user+"\n") {
				for k, v := range blockValues {
					vals[k] = v
				}
				for k, v := range h.sshdOverride {
					vals[k] = v
				}
			}
		}
		var b strings.Builder
		for _, k := range slices.Sorted(func(yield func(string) bool) {
			for k := range vals {
				if !yield(k) {
					return
				}
			}
		}) {
			fmt.Fprintf(&b, "%s %s\n", k, vals[k])
		}
		return setuptest.OK(b.String()), nil
	case setupx.Systemctl:
		switch {
		case len(args) == 3 && args[0] == "is-active":
			if (args[2] == "ssh.service" && h.sshService) || (args[2] == "ssh.socket" && h.sshSocket) {
				return setupx.Output{}, nil
			}
			return setupx.Output{Exit: 3}, nil
		case len(args) > 0 && args[0] == "show":
			d, _ := f.Get(slice)
			re := regexp.MustCompile(`MemoryMax=(\d+)G`)
			n := "infinity"
			if m := re.FindStringSubmatch(d); m != nil {
				g, _ := strconv.ParseUint(m[1], 10, 64)
				n = strconv.FormatUint(g<<30, 10)
			}
			return setuptest.OK("MemoryMax=" + n + "\nMemorySwapMax=0\n"), nil
		}
		return setupx.Output{}, nil
	}
	return f.Simulate(prog, args)
}

func pubLine(t *testing.T) string {
	t.Helper()
	pub, _, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	k, err := ssh.NewPublicKey(pub)
	if err != nil {
		t.Fatal(err)
	}
	return strings.TrimSpace(string(ssh.MarshalAuthorizedKey(k)))
}

func readOnlyPolicy() *policy.Policy {
	return &policy.Policy{MaxTier: policy.TierRead, Sandbox: policy.Sandbox{Landlock: policy.LandlockRequired},
		Limits: policy.Limits{MaxMemoryMB: 1024}, SHA256: polSHA}
}

// newHost is a fresh Debian-like target with the binaries and a policy in
// place and nothing installed (TARGET-SETUP §3, §5 done).
func newHost(t *testing.T) (h *host, keyLine string) {
	t.Helper()
	f := setuptest.New()
	h = &host{Fake: f, pol: readOnlyPolicy(), mem: 8 << 30, sshService: true, strictModes: "yes",
		checkOut: setuptest.OK("ok: serve would accept this install and policy\n")}
	f.Programs = h.programs
	for _, d := range []string{"/etc/ssh", "/etc/ssh/sshd_config.d", "/etc/systemd", "/etc/systemd/system", "/etc/shell-mcp", "/root", "/root/in"} {
		f.Dir(d, 0o755, 0, 0)
	}
	f.Dir("/etc/polkit-1", 0o755, 0, 0)
	f.Dir("/run/sshd", 0o755, 0, 0)
	f.Dir("/etc/polkit-1/rules.d", 0o750, 0, 990)
	f.Put(polPath, "invented policy\n", 0o644, 0, 0)
	hostLine := pubLine(t)
	f.Put("/etc/ssh/ssh_host_ed25519_key.pub", hostLine+" root@target-a\n", 0o644, 0, 0)
	line := pubLine(t)
	f.Put(keyPath, line+" shell-mcp\n", 0o644, 0, 0)
	return h, line
}

func baseArgs() []string {
	return []string{"--policy", polPath, "--principal", "readonly", "--from", "192.0.2.10", "--key", keyPath, "--uid", "60123", "--gid", "60123"}
}

type result struct {
	code   int
	out    string
	audit  []string
	before map[string]setuptest.File
}

func install(t *testing.T, h *host, extra ...string) result {
	t.Helper()
	o, err := setup.ParseFlags(append(baseArgs(), extra...), "/root")
	if err != nil {
		t.Fatalf("flags: %v", err)
	}
	var out, aud bytes.Buffer
	before := h.Snapshot()
	h.order = nil
	code := setup.Install(o, h, &out, &setupx.Auditor{Stderr: &aud, Component: "gate", DryRun: o.DryRun})
	var lines []string
	if aud.Len() > 0 {
		lines = strings.Split(strings.TrimSuffix(aud.String(), "\n"), "\n")
	}
	if l := h.Temps(); len(l) > 0 {
		t.Fatalf("temp files left: %v", l)
	}
	return result{code, out.String(), lines, before}
}

// TestInstallFresh: a fresh host gets exactly the hand steps' files, in
// TARGET-SETUP's order, with the key line last; the owner scan runs before
// groupadd; check-policy runs as the account; sshd is checked and
// reloaded.
func TestInstallFresh(t *testing.T) {
	h, line := newHost(t)
	r := install(t, h)
	if r.code != 0 {
		t.Fatalf("exit %d:\n%s", r.code, r.out)
	}
	k := strings.Fields(line)[1]
	want := map[string]string{
		dropPath: string(setup.DropIn("svc-shell")),
		slice:    "[Slice]\nMemoryMax=4G\nMemorySwapMax=0\n",
		keysPath: `restrict,from="192.0.2.10",command="/usr/local/bin/shell-mcp-gate serve --policy /etc/shell-mcp/read-only.yaml --principal readonly" ssh-ed25519 ` + k + " shell-mcp-readonly\n",
	}
	for p, w := range want {
		got, ok := h.Get(p)
		if !ok || got != w {
			t.Errorf("%s:\n%q\nwant\n%q", p, got, w)
		}
		if e := h.Files[p]; e.UID != 0 || e.GID != 0 || e.Mode != 0o644 {
			t.Errorf("%s: %d:%d %v", p, e.UID, e.GID, e.Mode)
		}
	}
	if e := h.Files[setup.KeysDir]; e == nil || e.Mode != os.ModeDir|0o755 || e.UID != 0 {
		t.Fatalf("keys directory %+v", e)
	}
	if _, ok := h.Get(setup.PolkitRule); ok {
		t.Fatal("a polkit rule for a policy without services.control")
	}
	pw, _ := h.Get("/etc/passwd")
	if !strings.Contains(pw, "svc-shell:x:60123:60123::/var/lib/svc-shell:/bin/sh\n") {
		t.Fatalf("passwd %q", pw)
	}
	order := strings.Join(h.order, "\n")
	for _, seq := range [][]string{
		{"owner-scan", "groupadd --gid 60123 svc-shell", "useradd --uid 60123 --gid 60123 --home-dir /var/lib/svc-shell --create-home --shell /bin/sh svc-shell", "usermod -L svc-shell"},
		{"usermod -L svc-shell", "mkdir /etc/systemd/system/user-60123.slice.d", "write " + slice, "/usr/bin/systemctl daemon-reload", "/usr/bin/systemctl show -p MemoryMax -p MemorySwapMax user-60123.slice", "check-policy"},
		{"check-policy", "write " + dropPath, "mkdir " + setup.KeysDir, "write " + keysPath, "sshd -t"},
		{"sshd -t", "sshd -T -C user=svc-shell,host=client.example.test,addr=192.0.2.10", "sshd -T -C user=shell-mcp-install-check,host=client.example.test,addr=192.0.2.10", "/usr/bin/systemctl reload ssh.service"},
	} {
		if !inOrder(h.order, seq) {
			t.Errorf("not in order %q:\n%s", seq, order)
		}
	}
	var lastWrite string
	for _, o := range h.order {
		if strings.HasPrefix(o, "write ") || strings.HasPrefix(o, "mkdir ") {
			lastWrite = o
		}
	}
	if lastWrite != "write "+keysPath {
		t.Fatalf("the last write is %q, want the key line", lastWrite)
	}
	if len(h.runAs) != 1 || !reflect.DeepEqual(h.runAs[0], &execx.Credential{UID: 60123, GID: 60123}) {
		t.Fatalf("check-policy ran as %+v", h.runAs)
	}
	if !reflect.DeepEqual(h.scanned, [][]uint32{{60123, 60123}}) {
		t.Fatalf("owner scan for %v", h.scanned)
	}
	if !strings.Contains(r.out, "SHELL_MCP_TARGET_HOST_KEYS=ssh-ed25519 SHA256:") || !strings.Contains(r.out, "keep this session open") {
		t.Fatalf("output:\n%s", r.out)
	}
	audit := strings.Join(r.audit, "\n")
	for _, s := range []string{`"object":"owner_scan","owner_scan":"full"`, `"object":"key","path":"` + keysPath, `"fingerprint":"SHA256:`, `"object":"sshd","path":"` + dropPath} {
		if !strings.Contains(audit, s) {
			t.Errorf("audit lacks %s:\n%s", s, audit)
		}
	}
	if strings.Contains(audit, k) {
		t.Fatal("the audit holds the key")
	}
}

func inOrder(have, want []string) bool {
	i := 0
	for _, h := range have {
		if i < len(want) && h == want[i] {
			i++
		}
	}
	return i == len(want)
}

// TestInstallSecondRunUnchanged: the same flags again change nothing and
// say so; a dry run changes nothing and runs only what reads.
func TestInstallSecondRunUnchanged(t *testing.T) {
	h, _ := newHost(t)
	if r := install(t, h); r.code != 0 {
		t.Fatalf("first run %d:\n%s", r.code, r.out)
	}
	writes := h.Writes
	r := install(t, h)
	if r.code != 0 || h.Writes != writes || !strings.Contains(r.out, "nothing to do: every item unchanged") {
		t.Fatalf("second run %d, %d writes:\n%s", r.code, h.Writes-writes, r.out)
	}
	for _, o := range h.order {
		if strings.HasPrefix(o, "groupadd") || strings.HasPrefix(o, "useradd") || strings.HasPrefix(o, "usermod") || strings.HasSuffix(o, "reload ssh.service") || strings.HasSuffix(o, "daemon-reload") || o == "owner-scan" {
			t.Fatalf("second run ran %q", o)
		}
	}
	for _, p := range []string{dropPath, slice, keysPath, setup.KeysDir} {
		if !strings.Contains(r.out, p+": unchanged") {
			t.Errorf("%s not reported unchanged:\n%s", p, r.out)
		}
	}
}

func TestInstallDryRun(t *testing.T) {
	h, _ := newHost(t)
	r := install(t, h, "--dry-run")
	if r.code != 0 {
		t.Fatalf("exit %d:\n%s", r.code, r.out)
	}
	if after := h.Snapshot(); !reflect.DeepEqual(after, r.before) {
		t.Fatal("the dry run changed the filesystem")
	}
	for _, o := range h.order {
		if !strings.HasPrefix(o, "sshd -T") && !strings.HasPrefix(o, "/usr/bin/systemctl is-active") && o != "owner-scan" {
			t.Fatalf("the dry run ran %q", o)
		}
	}
	for _, s := range []string{"would run /usr/sbin/groupadd --gid 60123 svc-shell", "file " + dropPath + " root:root 0644: create", "     | Match User svc-shell",
		"would run /usr/bin/systemctl reload ssh.service", "file " + keysPath + " root:root 0644: create"} {
		if !strings.Contains(r.out, s) {
			t.Errorf("dry run lacks %q:\n%s", s, r.out)
		}
	}
	if len(r.audit) != 0 {
		t.Fatalf("a dry run audited %v", r.audit)
	}
}

// TestTargetSetupBytes: the files install writes are byte for byte what
// TARGET-SETUP §4 and §7 write by hand (the hand steps' text, read from the
