func appendTo(h *host, p, line string) {
	v, _ := h.Get(p)
	h.Put(p, v+line+"\n", 0o644, 0, 0)
}

// setGroup replaces the group line of the same name.
func setGroup(h *host, line string) {
	v, _ := h.Get("/etc/group")
	name, _, _ := strings.Cut(line, ":")
	var out []string
	for _, l := range strings.Split(strings.TrimSuffix(v, "\n"), "\n") {
		if strings.HasPrefix(l, name+":") {
			l = line
		}
		out = append(out, l)
	}
	h.Put("/etc/group", strings.Join(out, "\n")+"\n", 0o644, 0, 0)
}

// existing makes svc-shell exist already with home and shell.
func existing(h *host, home, shell string) {
	appendTo(h, "/etc/passwd", "svc-shell:x:60123:60123::"+home+":"+shell)
	appendTo(h, "/etc/group", "svc-shell:x:60123:")
	h.Dir(home, 0o750, 60123, 60123)
}

// TestInstallRollback: when a check after a write fails, every file the
// run changed is restored and no temp file is left; the account stays.
func TestInstallRollback(t *testing.T) {
	for _, c := range []struct {
		name string
		mod  func(*host)
		want string
	}{
		{"the block is not in force", func(h *host) { h.sshdOverride = map[string]string{"permittty": "yes"} }, "the Match block is not in force"},
		{"check-policy FAILs", func(h *host) { h.checkOut = setupx.Output{Stdout: []byte("FAIL install: ...\n"), Exit: 1} }, "reports FAIL"},
		{"the keys file cannot be written", func(h *host) { h.FailWrite[keysPath] = errors.New("disk full") }, "disk full"},
		{"a read-back fails after the rename", func(h *host) { h.FailCommitted[dropPath] = errors.New("read-back differs") }, "read-back differs"},
	} {
		t.Run(c.name, func(t *testing.T) {
			h, _ := newHost(t)
			h.Dir(setup.KeysDir, 0o755, 0, 0)
			h.Put(keysPath, "# servers\n", 0o644, 0, 0)
			c.mod(h)
			r := install(t, h)
			if r.code != 1 || !strings.Contains(r.out, c.want) || !strings.Contains(r.out, "every file this run changed was restored") {
				t.Fatalf("exit %d:\n%s", r.code, r.out)
			}
			after := h.Snapshot()
			for p := range r.before {
				if p == "/etc/passwd" || p == "/etc/group" {
					continue
				}
				if !reflect.DeepEqual(after[p], r.before[p]) {
					t.Errorf("%s not restored", p)
				}
			}
			for p := range after {
				if _, ok := r.before[p]; !ok && p != "/var/lib/svc-shell" {
					t.Errorf("%s left behind", p)
				}
			}
			if !strings.Contains(r.out, "the account and groups this run created remain") {
				t.Fatalf("output:\n%s", r.out)
			}
		})
	}
}

