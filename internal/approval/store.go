package approval

import (
	"context"
	"errors"
	"log/slog"
	"time"
)

// Method is SHELL_MCP_APPROVAL_METHOD.
type Method string

// Methods.
const (
	MethodNone    Method = "none"
	MethodWeb     Method = "web"
	MethodConfirm Method = "confirm-argument"
)

// ConfirmApprover is the approver recorded when the model approves its own
// request under confirm-argument.
const ConfirmApprover = "model (confirm-argument)"

// Status is a record's state: pending → approved / declined / expired →
// used.
type Status string

// Statuses.
const (
	StatusPending  Status = "pending"
	StatusApproved Status = "approved"
	StatusDeclined Status = "declined"
	StatusExpired  Status = "expired"
	StatusUsed     Status = "used"
)

// Bounds (handoff §6.1, §6.2).
const (
	// MaxPendingPerPrincipal bounds the pending records of one principal.
	MaxPendingPerPrincipal = 5
	// MaxRecords bounds the store.
	MaxRecords = 256
	// PendingWait is how long a re-call waits for a pending record's
	// decision (never past its expiry).
	PendingWait = 20 * time.Second
	// MaxPreviewBytes bounds the preview fields shown on the page.
	MaxPreviewBytes = 16 << 10
	// MaxArgsBytes bounds the argument fields shown on the page.
	MaxArgsBytes = 16 << 10
	// MaxFieldBytes bounds one field's value on the page.
	MaxFieldBytes = 4096
)

// Errors of Request and Decide.
var (
	ErrTooManyPending = errors.New("too many pending approvals for this principal")
	ErrStoreFull      = errors.New("the approval store is full")
	ErrUnknown        = errors.New("unknown approval")
	ErrNotPending     = errors.New("the approval is no longer pending")
	ErrExpired        = errors.New("the approval has expired")
)

// Binding is what identifies a call: the principal, the tool, the resolved
// target and the SHA-256 of the canonical arguments.
type Binding struct {
	Principal  string
	Tool       string
	Target     string
	ArgsSHA256 string
}

// Request is what a first call asks approval for: its binding, the hashes
// of the preview and of the gate policy reported with it, and what the page
// shows, all generated by the server.
type Request struct {
	Binding
	PreviewSHA256 string
	PolicySHA256  string
	// ToolTitle and TargetHost come from the server's own definitions and
	// configuration.
	ToolTitle  string
	TargetHost string
	// Description is one line the server generated from the tool and the
	// canonical arguments.
	Description string
	// Args and Preview are the canonical arguments and the preview, as
	// fields.
	Args    []Field
	Preview []Field
}

// Record is a snapshot of one approval record.
type Record struct {
	ID string
	Request
	CreatedAt time.Time
	ExpiresAt time.Time
	Status    Status
	// Approver, DecidedAt and DecidedFrom are set on a decision: the
	// verified approver's name (or ConfirmApprover) and the client address.
	Approver    string
	DecidedAt   time.Time
	DecidedFrom string
	// CSRFToken is 128 random bits, required on both decisions.
	CSRFToken string
}

// Options configure a Store.
type Options struct {
	// TTL is SHELL_MCP_APPROVAL_TTL.
	TTL time.Duration
	// Method is recorded in the audit lines; under confirm-argument a
	// pending re-call does not wait (nobody else can decide).
	Method Method
	// Now is the clock (default time.Now).
	Now func() time.Time
	// Logger receives the audit lines (default: discard).
	Logger *slog.Logger
	// Wait overrides PendingWait (tests); zero means PendingWait.
	Wait time.Duration
	// OnCreate, when set, is called once for each new record (the
	// notifier), outside the store's lock.
	OnCreate func(Record)
}

// Store is the bounded in-memory approval store. It is safe for concurrent
// use; a restart (a new Store) forgets every record.
type Store struct {
	o Options
}

// NewStore returns an empty store.
func NewStore(o Options) *Store { return &Store{o: o} }

// Request creates a pending record for r, or returns the pending record of
// an identical request (same binding, preview and policy hashes). It logs
// "approval requested" for a new record.
func (s *Store) Request(r Request) (Record, error) { return Record{}, nil }

// Get returns a snapshot of the record with id.
func (s *Store) Get(id string) (Record, bool) { return Record{}, false }

// Decide approves or declines a pending, unexpired record as approver (a
// verified name), from a client address, and logs "approval decided".
func (s *Store) Decide(id string, approve bool, approver, from string) (Record, error) {
	return Record{}, nil
}

// Outcome is the result of a re-call's check.
type Outcome int

// Outcomes of Use.
const (
	// OutcomeUsed: the record was approved and matched, and is now used;
	// the caller compares a fresh preview and then executes.
	OutcomeUsed Outcome = iota + 1
	// OutcomePending: still pending after the wait.
	OutcomePending
	// OutcomeDeclined: the approver declined.
	OutcomeDeclined
	// OutcomeInvalid: unknown, expired, used or not matching the call.
	OutcomeInvalid
)

// UseResult is what Use returns. Record is set unless the id is unknown.
type UseResult struct {
	Outcome Outcome
	Record  Record
	Known   bool
	// Reason is a one-line message for an invalid outcome.
	Reason string
}

// Use runs a re-call's checks, in order (handoff §6.3): the record exists
// and is approved (a pending one waits, for a call that matches it); it is
// unexpired and unused; the call's binding equals the record's; then the
// record is marked used, atomically, before the caller sends anything.
// confirmAs, when not empty (confirm-argument), first approves a matching
// pending record as that approver, logging a WARN.
func (s *Store) Use(ctx context.Context, id string, b Binding, confirmAs, from string) UseResult {
	return UseResult{}
}

// Sweep marks every record past its expiry: a pending or approved one
// becomes expired (logged "approval expired"); records past expiry are
// removed.
func (s *Store) Sweep() {}

// Run sweeps every interval until ctx ends.
func (s *Store) Run(ctx context.Context, interval time.Duration) {}

// expireAt sets a record's expiry (tests).
func (s *Store) expireAt(id string, t time.Time) {}
